        public void CreateFile(List<Payment_Def.TmpElec> ttTmpElecRows, int eftHeadUID, string outputFile)
        {
            /* create the payment file */
            outputFile = LibGetFileName.Get(outputFile, FileName.ServerFileType.Custom);

            EI.Payment_Def.TmpElec tmpElec = (from ttTmpElec_Row in ttTmpElecRows select ttTmpElec_Row).FirstOrDefault();
            if (tmpElec == null)
            {
                throw new BLException(GlobalStrings.InterErrorTmpElecHasNoRecords);
            }

            var vendorBankList = ttTmpElecRows.Select(r => r.VendorBankID).Distinct().ToList();
            var vendorNumList = ttTmpElecRows.Select(r => r.VendorNum).Distinct().ToList();
            var queryVendBanks = VendBankQuery(Session.CompanyID)
                                 .Where(row => vendorBankList.Any(r => r.KeyEquals(row.VendorBankID)) &&
                                               vendorNumList.Any(r => r == row.VendorNum));

            var emptyBankContries = queryVendBanks
                                    .Where(r => r.BCountryNum == 0);
            string emptyBankContriesMessage = string.Concat(emptyBankContries.Select(r => Environment.NewLine + " SupplierID = " + r.VendorID + " BankID = " + r.VendorBankID));
            if (!string.IsNullOrEmpty(emptyBankContriesMessage))
            {
                throw new BLException(GlobalStrings.AValidCountryOfTheBankOfTheSupplIsRequi + emptyBankContriesMessage);
            }

            if (queryVendBanks.Any(r => r.ISOCode.KeyEquals("US")) &&
               queryVendBanks.Any(r => !r.ISOCode.KeyEquals("US")))
            {
                throw new BLException(Strings.DoNotMixDomesticInternatPayments);
            }
            if (queryVendBanks.Any(r => !r.ISOCode.KeyEquals("US")))
            {
                throw new BLException(Strings.UseACHInternationalEI);
            }

            /* build the info containing the payments */
            buildInfo(ttTmpElecRows);

            using (var writeFileLib = new writeFileLib(outputFile))
            {
                /* output the payment details*/
                foreach (var outFileLine in EISFCommon.ttOutFileLineRows)
                {
                    writeFileLib.FileWriteLine(outFileLine.Line_out);
                }
                writeFileLib.FileClose();
            }
        }

