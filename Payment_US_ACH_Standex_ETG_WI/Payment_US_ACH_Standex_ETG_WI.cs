        private IEnumerable<string> split(string text, int size)
        {
            for (var i = 0; i < text.Length; i += size)
            {
                yield return text.Substring(i, Math.Min(size, text.Length - i));
            }
        }

        /// <summary>
        /// Allowable characters
        ///  Characters used in ACH records are restricted to the following:
        ///     * Numbers 0-9.
        ///     * Letters a-z and A-Z. (Some fields require uppercase characters, and we recommend using uppercase letters for all fields.)
        ///     * Space.
        ///     * Special characters with an ASCII value greater than hexadecimal 1F. Occurrences of values ASCII 00-1F are not valid.
        /// </summary>
        /// <param name="inpString">Input string</param>
        /// <returns></returns>
        private string alpha(string inpString)
        {
            StringBuilder sb = new StringBuilder();
            foreach (char c in inpString)
            {
                if ((int)c > 31)
                {
                    sb.Append(c);
                }
            }
            return sb.ToString().ToUpperInvariant();
        }
        private string numeric(decimal decVal, int len)
        {
            return Compatibility.Convert.ToString(Math.Abs(decVal), ".99".PadLeft(len + 1, '9')).Replace(".", string.Empty);
        }
        private string numeric(string strVal, int len)
        {
            StringBuilder sb = new StringBuilder();
            foreach (char c in strVal)
            {
                if (c >= '0' && c <= '9')
                {
                    sb.Append(c);

                }
            }

            string result = sb.ToString().SubString(0, len);
            return result.Length < len ? result.PadLeft(len, '0') : result;
        }
        private string numeric(int intVal, int len)
        {
            return numeric(intVal.ToString(), len);
        }
        private string numeric(long longVal, int len)
        {
            return numeric(longVal.ToString(), len);
        }

        private string getISOCurrencyCode(string currCode)
        {
            Currency currency = Currency.FindFirstByPrimaryKey(Db, Session.CompanyID, currCode);
            if (currency != null)
            {
                if (string.IsNullOrEmpty(currency.ISOCurrCode))
                    throw new BLException(Strings.ISOCodeIsNotDefined(currCode));
                return currency.ISOCurrCode;
            }
            else
                throw new BLException(Strings.ISOCodeIsNotDefined(currCode));

        }
        private string formatAmount(decimal amount)
        {
            return Compatibility.Convert.ToString(amount, "9.99");
        }
